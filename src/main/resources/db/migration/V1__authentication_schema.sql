    CONSTRAINT ck_binding_platform CHECK (platform IN ('ANDROID','IOS')),
    CONSTRAINT ck_binding_assurance CHECK (possession_assurance = 'MFA_KEY_POSSESSION' AND platform_assurance IN ('NONE','HARDWARE_KEY','APP_INSTANCE_BOUND')),
    CONSTRAINT ck_device_binding_version CHECK (version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_device_binding_device_security_version CHECK (device_security_version BETWEEN 0 AND 9007199254740991),
    INDEX ix_binding_list (subject_id, app_id, status, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

CREATE TABLE auth_device_key (
    id BINARY(16) NOT NULL,
    subject_id BINARY(16) NOT NULL,
    app_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    binding_id BINARY(16) NULL,
    purpose VARCHAR(24) NOT NULL,
    public_key_spki VARBINARY(1024) NOT NULL,
    jkt BINARY(32) NOT NULL,
    algorithm VARCHAR(16) NOT NULL,
    status VARCHAR(16) NOT NULL,
    live_slot TINYINT GENERATED ALWAYS AS (CASE WHEN status = 'ACTIVE' THEN 1 ELSE NULL END) STORED,
    expires_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_device_key_jkt UNIQUE (jkt),
    CONSTRAINT uq_device_key_owner UNIQUE (id, subject_id, app_id),
    CONSTRAINT uq_device_key_binding_owner UNIQUE (id, binding_id, subject_id, app_id),
    CONSTRAINT uq_device_key_active UNIQUE (binding_id, purpose, live_slot),
    CONSTRAINT fk_device_key_subject_app FOREIGN KEY (subject_id, app_id) REFERENCES auth_subject_app (subject_id, app_id),
    CONSTRAINT fk_device_key_binding FOREIGN KEY (binding_id, subject_id, app_id) REFERENCES auth_device_binding (id, subject_id, app_id),
    CONSTRAINT ck_device_key_purpose CHECK (purpose IN ('REQUEST','DEVICE_POSSESSION') AND (purpose <> 'DEVICE_POSSESSION' OR binding_id IS NOT NULL)),
    CONSTRAINT ck_device_key_status CHECK (status IN ('ACTIVE','REVOKED','EXPIRED') AND algorithm = 'ES256'),
    CONSTRAINT ck_device_key_version CHECK (version BETWEEN 0 AND 9007199254740991)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

CREATE TABLE auth_login_journey (
