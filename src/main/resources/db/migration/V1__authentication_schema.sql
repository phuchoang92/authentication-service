    source VARCHAR(24) NOT NULL DEFAULT 'NATIVE',
    owner_scope BINARY(32) NOT NULL,
    kind VARCHAR(40) NOT NULL,
    idempotency_digest BINARY(32) NOT NULL,
    command_digest BINARY(32) NOT NULL,
    request_jkt BINARY(32) NULL,
    state VARCHAR(24) NOT NULL,
    provider_operation_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL,
    protected_context MEDIUMBLOB NULL,
    result_digest BINARY(32) NULL,
    deadline DATETIME(6) NOT NULL,
    lease_until DATETIME(6) NULL,
    fence BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_operation_idempotency UNIQUE (owner_scope, kind, idempotency_digest),
    CONSTRAINT uq_operation_owner UNIQUE (id, subject_id, app_id),
    CONSTRAINT uq_operation_subject UNIQUE (id, subject_id),
    CONSTRAINT uq_operation_request_key UNIQUE (id, request_jkt),
    CONSTRAINT fk_operation_journey FOREIGN KEY (journey_id) REFERENCES auth_login_journey (id),
    CONSTRAINT fk_operation_journey_owner FOREIGN KEY (journey_id, subject_id, app_id) REFERENCES auth_login_journey (id, subject_id, app_id),
    CONSTRAINT fk_operation_subject_app FOREIGN KEY (subject_id, app_id) REFERENCES auth_subject_app (subject_id, app_id),
    CONSTRAINT fk_operation_subject FOREIGN KEY (subject_id) REFERENCES auth_subject (id),
    CONSTRAINT ck_operation_source CHECK ((source = 'NATIVE' AND app_id IS NOT NULL AND request_jkt IS NOT NULL) OR (source = 'CUSTOMER_EVENT' AND kind = 'CUSTOMER_STATUS_CHANGED' AND subject_id IS NOT NULL AND app_id IS NULL AND request_jkt IS NULL AND journey_id IS NULL)),
    CONSTRAINT ck_operation_state CHECK (state IN ('RESERVED','DISPATCHED','UNCERTAIN','CONFIRMED','REJECTED','COMPLETED')),
    CONSTRAINT ck_operation_version CHECK (version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_operation_fence CHECK (fence BETWEEN 0 AND 9007199254740991),
    INDEX ix_operation_work (state, lease_until, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

