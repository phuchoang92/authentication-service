    route VARCHAR(24) NULL,
    context_digest BINARY(32) NULL,
    protected_context MEDIUMBLOB NULL,
    credential_deadline DATETIME(6) NOT NULL,
    journey_deadline DATETIME(6) NOT NULL,
    customer_security_version BIGINT NULL,
    credential_security_version BIGINT NULL,
    device_security_version BIGINT NULL,
    fence BIGINT NOT NULL DEFAULT 0,
    version BIGINT NOT NULL DEFAULT 0,
