CREATE TABLE auth_subject (
    id BINARY(16) NOT NULL,
    customer_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    customer_status_version BIGINT NOT NULL,
    customer_last_block_version BIGINT NOT NULL DEFAULT 0,
    customer_status_checked_at DATETIME(6) NOT NULL,
    status VARCHAR(24) NOT NULL,
    customer_security_version BIGINT NOT NULL DEFAULT 0,
    credential_security_version BIGINT NOT NULL DEFAULT 0,
    policy_version VARCHAR(64) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_subject_customer UNIQUE (customer_id),
    CONSTRAINT ck_subject_customer_version CHECK (customer_status_version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_subject_block_watermark CHECK (customer_last_block_version BETWEEN 0 AND customer_status_version),
    CONSTRAINT ck_subject_status CHECK (status IN ('ELIGIBLE','BLOCKED','CLOSED')),
    CONSTRAINT ck_subject_version CHECK (version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_subject_customer_security_version CHECK (customer_security_version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_subject_credential_security_version CHECK (credential_security_version BETWEEN 0 AND 9007199254740991)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

