    CONSTRAINT uq_journey_owner UNIQUE (id, subject_id, app_id),
    CONSTRAINT fk_journey_subject_app FOREIGN KEY (subject_id, app_id) REFERENCES auth_subject_app (subject_id, app_id),
    CONSTRAINT fk_journey_binding FOREIGN KEY (resolved_binding_id, subject_id, app_id) REFERENCES auth_device_binding (id, subject_id, app_id),
    CONSTRAINT ck_journey_binding_owner CHECK (resolved_binding_id IS NULL OR subject_id IS NOT NULL),
    CONSTRAINT ck_journey_method CHECK (method IN ('PASSWORD','BIOMETRIC') AND purpose IN ('LOGIN','UNLOCK')),
    CONSTRAINT ck_journey_route CHECK (route IS NULL OR route IN ('LAST_TRUSTED','OTHER_TRUSTED','NEW_DEVICE')),
    CONSTRAINT ck_journey_state CHECK (state IN ('INITIALIZED','CREDENTIAL_PROCESSING','PENDING_MFA','PENDING_RESET','FINALIZING','COMPLETED','FAILED','CANCELLED','EXPIRED')),
    CONSTRAINT ck_login_journey_version CHECK (version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_login_journey_fence CHECK (fence BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_login_journey_customer_security_version CHECK (customer_security_version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_login_journey_credential_security_version CHECK (credential_security_version BETWEEN 0 AND 9007199254740991),
    CONSTRAINT ck_login_journey_device_security_version CHECK (device_security_version BETWEEN 0 AND 9007199254740991),
    INDEX ix_journey_recovery (state, updated_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_as_cs;

