INSERT INTO TRUSTED_DEVICE_REVOKE (
    ID, CUSTOMER_ID, CHANNEL, CLIENT_DEVICE_ID_LOOKUP, CLIENT_DEVICE_ID_LOOKUP_KEY_ID,
    CLIENT_DEVICE_ID_CIPHERTEXT, CLIENT_DEVICE_ID_KEY_ID, PLATFORM, STATUS, TRUST_LEVEL,
    TRUSTED_AT, EXPIRES_AT, LAST_SUCCESSFUL_LOGIN_AT, PRIMARY_CRYPTO_SUITE, PRIMARY_PUBLIC_KEY,
    PRIMARY_KEY_ID, VERSION, CREATED_AT, UPDATED_AT
)
SELECT ID, CUSTOMER_ID, CHANNEL, CLIENT_DEVICE_ID_LOOKUP, CLIENT_DEVICE_ID_LOOKUP_KEY_ID,
       CLIENT_DEVICE_ID_CIPHERTEXT, CLIENT_DEVICE_ID_KEY_ID, PLATFORM, STATUS, TRUST_LEVEL,
       TRUSTED_AT, EXPIRES_AT, LAST_SUCCESSFUL_LOGIN_AT, PRIMARY_CRYPTO_SUITE, PRIMARY_PUBLIC_KEY,
       PRIMARY_KEY_ID, VERSION, CREATED_AT, UPDATED_AT
FROM TRUSTED_DEVICE
WHERE STATUS = 'REVOKED';

UPDATE PRIMARY_TRUSTED_DEVICE primary_device
LEFT JOIN TRUSTED_DEVICE device
  ON device.ID = primary_device.PRIMARY_DEVICE_ID
 AND device.CUSTOMER_ID = primary_device.CUSTOMER_ID
 AND device.CHANNEL = primary_device.CHANNEL
 AND device.STATUS IN ('ACTIVE', 'SUSPENDED')
 AND device.TRUST_LEVEL = 'TRUSTED'
SET primary_device.PRIMARY_DEVICE_ID = NULL,
    primary_device.ASSIGNED_AT = NULL,
    primary_device.PRIMARY_ENROLLMENT_ID = NULL,
    primary_device.FACE_AUTHENTICATED = FALSE,
    primary_device.PRIMARY_MODE = NULL,
    primary_device.AUTHORITY_VERSION = primary_device.AUTHORITY_VERSION + 1,
    primary_device.UPDATED_AT = UTC_TIMESTAMP(6)
WHERE primary_device.PRIMARY_DEVICE_ID IS NOT NULL AND device.ID IS NULL;

-- Existing DEVICE_EXPIRED / DEVICE_REPLACED audit rows retain their original binding IDs.
DELETE FROM TRUSTED_DEVICE WHERE STATUS IN ('PENDING', 'EXPIRED', 'REVOKED');
