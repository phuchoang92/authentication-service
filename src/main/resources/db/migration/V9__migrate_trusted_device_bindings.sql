-- DML only. Preserve open approvals with a matching candidate from the old binding.
UPDATE TRUSTED_DEVICE_ENROLLMENT enrollment
JOIN TRUSTED_DEVICE device
  ON device.ID = enrollment.TARGET_DEVICE_ID
 AND device.CUSTOMER_ID = enrollment.CUSTOMER_ID
 AND device.CHANNEL = enrollment.CHANNEL
 AND device.CLIENT_DEVICE_ID_LOOKUP = enrollment.REQUESTER_CLIENT_DEVICE_ID_LOOKUP
 AND device.CLIENT_DEVICE_ID_LOOKUP_KEY_ID = enrollment.CLIENT_DEVICE_ID_LOOKUP_KEY_ID
SET enrollment.REQUESTER_CLIENT_DEVICE_ID_CIPHERTEXT = device.CLIENT_DEVICE_ID_CIPHERTEXT,
    enrollment.REQUESTER_CLIENT_DEVICE_ID_KEY_ID = device.CLIENT_DEVICE_ID_KEY_ID,
    enrollment.CANDIDATE_PLATFORM = device.PLATFORM,
    enrollment.CANDIDATE_PUBLIC_KEY = device.PRIMARY_PUBLIC_KEY,
    enrollment.TARGET_DEVICE_ID = CASE WHEN device.STATUS = 'PENDING' THEN NULL ELSE device.ID END,
    enrollment.VERSION = enrollment.VERSION + 1
WHERE enrollment.PURPOSE = 'TRUST_DEVICE_APPROVAL'
  AND enrollment.STATE IN ('WAITING_APPROVAL', 'WAITING_AUTHORIZATION')
  AND enrollment.EXPIRES_AT > UTC_TIMESTAMP(6)
  AND device.STATUS IN ('PENDING', 'ACTIVE', 'SUSPENDED')
  AND device.PRIMARY_PUBLIC_KEY IS NOT NULL
  AND device.PRIMARY_PUBLIC_KEY <> '';

-- Close entries whose deadline passed or whose target could not be migrated.
UPDATE TRUSTED_DEVICE_ENROLLMENT
SET STATE = CASE WHEN EXPIRES_AT <= UTC_TIMESTAMP(6) THEN 'EXPIRED' ELSE 'FAILED' END,
    VERSION = VERSION + 1
WHERE PURPOSE = 'TRUST_DEVICE_APPROVAL'
  AND STATE IN ('WAITING_APPROVAL', 'WAITING_AUTHORIZATION')
  AND (EXPIRES_AT <= UTC_TIMESTAMP(6) OR CANDIDATE_PUBLIC_KEY IS NULL);

-- Legacy races could leave multiple open requests for one installation. Keep the newest.
UPDATE TRUSTED_DEVICE_ENROLLMENT older
JOIN TRUSTED_DEVICE_ENROLLMENT newer
  ON newer.CUSTOMER_ID = older.CUSTOMER_ID
 AND newer.CHANNEL = older.CHANNEL
 AND newer.PURPOSE = older.PURPOSE
 AND newer.REQUESTER_CLIENT_DEVICE_ID_LOOKUP = older.REQUESTER_CLIENT_DEVICE_ID_LOOKUP
 AND (newer.CREATED_AT > older.CREATED_AT OR (newer.CREATED_AT = older.CREATED_AT AND newer.ID > older.ID))
SET older.STATE = 'FAILED', older.VERSION = older.VERSION + 1
WHERE older.PURPOSE = 'TRUST_DEVICE_APPROVAL'
  AND older.STATE IN ('WAITING_APPROVAL', 'WAITING_AUTHORIZATION')
  AND newer.STATE IN ('WAITING_APPROVAL', 'WAITING_AUTHORIZATION');

