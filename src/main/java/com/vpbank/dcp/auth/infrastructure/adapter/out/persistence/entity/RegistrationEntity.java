package com.vpbank.dcp.auth.infrastructure.adapter.out.persistence.entity;

import com.vpbank.dcp.auth.domain.enums.RegistrationState;
import com.vpbank.dcp.auth.infrastructure.adapter.out.persistence.common.AuditedEntity;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import java.time.Instant;
import java.util.UUID;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;

/** Row of CUSTOMER_AUTHENTICATION_REGISTRATION (design phase 1). State changes only through {@link #applyStep}. */
@Entity
@Table(name = "CUSTOMER_AUTHENTICATION_REGISTRATION")
@Getter
@Builder
@NoArgsConstructor(access = AccessLevel.PROTECTED)
@AllArgsConstructor(access = AccessLevel.PRIVATE)
public class RegistrationEntity extends AuditedEntity {
    @Id
    @Column(name = "REQUEST_ID", columnDefinition = "BINARY(16)", nullable = false)
    private UUID requestId;

    @Column(name = "CUSTOMER_ID", length = 16, nullable = false)
    private String customerId;

    @Column(name = "USERNAME", length = 64, nullable = false)
    private String userName;

    @Column(name = "IDENTITY_ISSUER")
    private String identityIssuer;

    @Column(name = "IDENTITY_SUBJECT")
    private String identitySubject;

    @Enumerated(EnumType.STRING)
    @Column(name = "STATE", length = 24, nullable = false)
    private RegistrationState state;

    /** Generated by MySQL: 1 while the request is open, NULL once READY or FAILED. Read-only here. */
    @Column(name = "OPEN_SLOT", insertable = false, updatable = false)
    private Byte openSlot;

    @Column(name = "REQUEST_DIGEST", columnDefinition = "BINARY(32)", nullable = false)
    private byte[] requestDigest;

    @Column(name = "EXPIRES_AT", nullable = false)
    private Instant expiresAt;

    @Version
    @Column(name = "VERSION", nullable = false)
    private long version;

    /** Copies one step decided by the aggregate; the only way this row changes. */
    public void applyStep(RegistrationState state, String identityIssuer, String identitySubject) {
        this.state = state;
        this.identityIssuer = identityIssuer;
        this.identitySubject = identitySubject;
    }
}
