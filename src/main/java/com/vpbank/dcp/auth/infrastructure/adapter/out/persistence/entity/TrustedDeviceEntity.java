package com.vpbank.dcp.auth.infrastructure.adapter.out.persistence.entity;

import com.vpbank.dcp.auth.infrastructure.adapter.out.persistence.common.AuditedEntity;
import com.vpbank.dcp.auth.domain.model.DevicePlatform;
import com.vpbank.dcp.auth.domain.model.DeviceStatus;
import com.vpbank.dcp.auth.domain.model.TrustLevel;
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lombok.AccessLevel;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;

import java.time.Instant;
import java.util.UUID;

/**
 * Row of TRUSTED_DEVICE (phase 3). The app's device ID is never stored in clear: HMAC for lookup,
 * AEAD ciphertext for display, each with its key ID. The public key columns hold the device's
 * P-256 JWK when the app sent one.
 */
@Entity
@Table(name = "TRUSTED_DEVICE")
@Getter
@Builder
@NoArgsConstructor(access = AccessLevel.PROTECTED)
@AllArgsConstructor(access = AccessLevel.PRIVATE)
public class TrustedDeviceEntity extends AuditedEntity {
    public static final String JWK_SUITE = "P-256-JWK";

    @Id
    @Column(name = "ID", columnDefinition = "BINARY(16)", nullable = false)
    private UUID id;

    @Column(name = "CUSTOMER_ID", length = 16, nullable = false)
    private String customerId;

    @Column(name = "CHANNEL", length = 64, nullable = false)
    private String channel;

    @Column(name = "CLIENT_DEVICE_ID_LOOKUP", columnDefinition = "BINARY(32)", nullable = false)
    private byte[] clientDeviceIdLookup;

    @Column(name = "CLIENT_DEVICE_ID_LOOKUP_KEY_ID", length = 64, nullable = false)
    private String clientDeviceIdLookupKeyId;

    @Column(name = "CLIENT_DEVICE_ID_CIPHERTEXT", columnDefinition = "VARBINARY(512)", nullable = false)
    private byte[] clientDeviceIdCiphertext;

    @Column(name = "CLIENT_DEVICE_ID_KEY_ID", length = 64, nullable = false)
    private String clientDeviceIdKeyId;

    @Enumerated(EnumType.STRING)
    @Column(name = "PLATFORM", length = 16, nullable = false)
    private DevicePlatform platform;

    @Enumerated(EnumType.STRING)
    @Column(name = "STATUS", length = 24, nullable = false)
    private DeviceStatus status;

    /** Generated by MySQL: 1 while PENDING/ACTIVE/SUSPENDED, NULL for history. Read-only here. */
    @Column(name = "LIVE_SLOT", insertable = false, updatable = false)
    private Byte liveSlot;

    @Enumerated(EnumType.STRING)
    @Column(name = "TRUST_LEVEL", length = 24, nullable = false)
    private TrustLevel trustLevel;

    @Column(name = "TRUSTED_AT")
    private Instant trustedAt;

    @Column(name = "EXPIRES_AT", nullable = false)
    private Instant expiresAt;

    @Column(name = "LAST_SUCCESSFUL_LOGIN_AT")
    private Instant lastSuccessfulLoginAt;

    @Column(name = "PRIMARY_CRYPTO_SUITE", length = 96)
    private String primaryCryptoSuite;

    @Column(name = "PRIMARY_PUBLIC_KEY", length = 2048)
    private String primaryPublicKey;

    @Column(name = "PRIMARY_KEY_ID", length = 128)
    private String primaryKeyId;

    @Version
    @Column(name = "VERSION", nullable = false)
    private long version;

    /** Copies the state the aggregate decided; the only way this row changes. */
    public void applyState(DeviceStatus status, TrustLevel trustLevel, Instant trustedAt, Instant expiresAt,
                           Instant lastSuccessfulLoginAt) {
        this.status = status;
        this.trustLevel = trustLevel;
        this.trustedAt = trustedAt;
        this.expiresAt = expiresAt;
        this.lastSuccessfulLoginAt = lastSuccessfulLoginAt;
    }
}
